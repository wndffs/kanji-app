function component(
  key: string,
  symbol: string,
  nameRu: string,
  nameEn: string,
  shapeRu: string,
  shapeEn: string,
  mnemonicRu: string,
  mnemonicEn: string,
): MainCourseComponentContent {
  return {
    key: `component-${key}`,
    symbol,
    displayName: { ru: nameRu, en: nameEn },
    shapeDescription: { ru: shapeRu, en: shapeEn },
    meaning: { ru: nameRu, en: nameEn },
    mnemonic: { ru: mnemonicRu, en: mnemonicEn },
  };
}

function kanji(
  character: string,
  ru: readonly [string, ...string[]],
  en: readonly [string, ...string[]],
  source: string,
  primary: string,
  componentKeys: readonly string[],
  meaningRu: string,
  meaningEn: string,
  readingRu: string,
  readingEn: string,
  sourceType: "ja_on" | "ja_kun" = "ja_on",
): Omit<MainCourseKanjiContent, "levelNumber" | "sortOrder"> {
  return {
    character,
    meanings: { ru: { primary: ru[0], accepted: ru }, en: { primary: en[0], accepted: en } },
    reading: { source, sourceType, primary, accepted: [primary] },
    componentKeys: componentKeys.map((key) => `component-${key}`),
    meaningMnemonic: { ru: meaningRu, en: meaningEn },
    readingMnemonic: { ru: readingRu, en: readingEn },
    requireStrokeData: true,
  };
}
