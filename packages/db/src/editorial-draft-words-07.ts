import { type MainCourseWordBatch, type MainCourseWordContent } from "./main-course-word-content";

export type EditorialWordDraft = Omit<MainCourseWordContent, "jmdictEntryId"> & {
  readonly jmdictEntryId: null;
};
export type EditorialWordDraftBatch = Omit<MainCourseWordBatch, "words"> & {
  readonly words: readonly EditorialWordDraft[];
};

function word(
  expression: string,
  reading: string,
  ru: string,
  en: string,
  meaningRu: string,
  meaningEn: string,
  readingRu: string,
  readingEn: string,
  example: readonly [string, string, string, string],
  alternatives: { readonly ru?: readonly string[]; readonly en?: readonly string[] } = {},
): Omit<EditorialWordDraft, "sortOrder"> {
  return {
    expression,
    reading,
    jmdictEntryId: null,
    meanings: {
      ru: { primary: ru, accepted: [ru, ...(alternatives.ru ?? [])] },
      en: { primary: en, accepted: [en, ...(alternatives.en ?? [])] },
    },
    meaningMnemonic: { ru: meaningRu, en: meaningEn },
    readingMnemonic: { ru: readingRu, en: readingEn },
    meaningHint: { ru: `Здесь изучаем значение «${ru}».`, en: `Here learn the meaning '${en}'.` },
    readingHint: {
      ru: `Напишите всё слово каной: ${reading}.`,
      en: `Write the entire word in kana: ${reading}.`,
    },
    example: {
      japaneseText: example[0],
      readingText: example[1],
      translationRu: example[2],
      translationEn: example[3],
    },
  };
}

