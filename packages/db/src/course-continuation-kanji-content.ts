// Frozen ranges of the 25 older vocabulary manifests, not a reservation of future levels.
const PRIOR_WORD_RANGES: readonly (readonly [number, number, number])[] = [
  [5, 1, 80],
  [6, 1, 40],
  [10, 1, 20],
  [12, 1, 20],
  [15, 1, 20],
  [21, 1, 20],
  [27, 21, 40],
  [30, 41, 80],
  [33, 1, 80],
  [37, 1, 80],
  [38, 1, 80],
];

export function buildCourseContinuationKanji(
  previous: readonly MainCourseContentBatch[],
): MainCourseContentBatch {
  const priorComponents = previous.flatMap((b) =>
    b.components.map((c, i) => ({
      ...c,
      level: b.componentLevelNumber,
      order: (b.componentSortOrderStart ?? 1) + i,
    })),
  );
  const components = CUES.map(([symbol, ru, en, shapeRu, shapeEn]) => ({
    key: `component-continuation-${symbol.codePointAt(0)!.toString(16)}`,
    symbol,
    displayName: { ru, en },
    meaning: { ru, en },
    shapeDescription: { ru: shapeRu, en: shapeEn },
    mnemonic: {
      ru: `Зрительный образ «${ru}»: ${shapeRu}. Это условное имя формы, не этимология.`,
      en: `Visual image '${en}': ${shapeEn}. This is a shape label, not etymology.`,
    },
  }));
  const componentMap = new Map(
    [...priorComponents, ...components.map((c) => ({ ...c, level: 1, order: 0 }))].map((c) => [
      c.symbol,
      c,
    ]),
  );
  const occupied = new Set<string>([
    ...priorComponents.map((c) => `${c.level}:${c.order}`),
    ...previous.flatMap((b) => b.kanji.map((k) => `${k.levelNumber}:${k.sortOrder}`)),
    ...PRIOR_WORD_RANGES.flatMap(([l, start, end]) =>
      Array.from({ length: end - start + 1 }, (_, i) => `${l}:${start + i}`),
    ),
  ]);
  const counts = new Map<number, number>();
  for (const k of previous.flatMap((b) => b.kanji))
    counts.set(k.levelNumber, (counts.get(k.levelNumber) ?? 0) + 1);
  const componentStart =
    Math.max(0, ...priorComponents.filter((c) => c.level === 1).map((c) => c.order)) + 1;
  components.forEach((_, i) => occupied.add(`1:${componentStart + i}`));
  return {
    id: "full-course-kanji-continuation",
    version: "1",
    authoredAt: "2026-11-01",
    reviewedAt: "2026-11-01",
    reviewNotes:
      "Independently AI-reviewed RU/EN meanings, visual cues, phonology and pinned KANJIDIC2/KanjiVG evidence; corrected near-misses and component descriptions. No human linguistic certification or publication receipt is claimed.",
    sourceFile: "packages/db/src/course-continuation-kanji-content.ts",
    courseSlug: "japanese-ru-n2",
    componentLevelNumber: 1,
    componentSortOrderStart: componentStart,
    components,
    kanji: CONTINUATION_KANJI.map(
      ([character, source, ru, en, shapes, imageRu, imageEn, soundRu, soundEn, word, kana]) => {
        const cues = shapes.map((s) => {
          const c = componentMap.get(s);
          if (!c) throw new Error(`Missing cue ${s} for ${character}`);
          return c;
        });
        let level = Math.max(2, ...cues.map((c) => c.level + 1));
        while (level <= 60 && (counts.get(level) ?? 0) >= 40) level++;
        if (level > 60) throw new Error("No free kanji capacity in the 60-level course");
        let order = 1;
        while (occupied.has(`${level}:${order}`)) order++;
        occupied.add(`${level}:${order}`);
        counts.set(level, (counts.get(level) ?? 0) + 1);
        return {
          character,
          levelNumber: level,
          sortOrder: order,
          meanings: {
            ru: {
              primary: ru[0]!,
              accepted: ru,
              ...(character === "笑"
                ? {
                    blocked: [
                      {
                        text: "сменяться",
                        reason: "Изменяться по очереди — не смеяться и не улыбаться.",
                      },
                    ],
                  }
                : {}),
            },
            en: { primary: en[0]!, accepted: en },
          },
          reading: {
            source,
            sourceType: /[ァ-ヶ]/u.test(source) ? ("ja_on" as const) : ("ja_kun" as const),
            primary: normalizeJapaneseReading(source),
            accepted: [normalizeJapaneseReading(source)],
          },
          componentKeys: cues.map((c) => c.key),
          meaningMnemonic: {
            ru: `Образ для памяти, не этимология: ${imageRu} Связи называют зрительные опоры, не полный состав штрихов.`,
            en: `Memory image, not etymology: ${imageEn} Linked forms are visual cues, not a complete stroke decomposition.`,
          },
          readingMnemonic: {
            ru: `${soundRu} Закрепите в слове ${word}（${kana}）.`,
            en: `${soundEn} Reinforce it in ${word} (${kana}).`,
          },
          requireStrokeData: true,
        };
      },
    ),
  };
}
