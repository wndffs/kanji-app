export const EXPANSION_READING_ALIGNMENTS: readonly ExpansionReadingAlignment[] = REVIEWED_ROWS.map(
  ([character, kanjiReading, expression, wordReading, characterIndex, readingOffset]) => ({
    character,
    kanjiReading,
    expression,
    wordReading,
    characterIndex,
    readingOffset,
  }),
);

export function isReviewedExpansionReadingAlignment(link: ExpansionReadingAlignment): boolean {
  const expected = REVIEWED_ROWS.find((row) => row[0] === link.character);
  return (
    expected !== undefined &&
    expected[1] === link.kanjiReading &&
    expected[2] === link.expression &&
    expected[3] === link.wordReading &&
    expected[4] === link.characterIndex &&
    expected[5] === link.readingOffset &&
    [...link.expression][link.characterIndex] === link.character &&
    link.wordReading.slice(link.readingOffset, link.readingOffset + link.kanjiReading.length) ===
      link.kanjiReading
  );
}
